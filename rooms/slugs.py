"""Формирование slug (URL-идентификатора) аудитории (ПР10).

Конвертер <slug:slug> принимает только латиницу, цифры, «-» и «_», а
номера аудиторий бывают с русскими буквами («12а»). Поэтому номер
сначала переводится в латиницу простой таблицей транслитерации.
Библиотека unidecode не нужна: проект обходится стандартными средствами.
"""

from django.utils.text import slugify

# Транслитерация строчных русских букв (регистр понижается заранее).
TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e",
    "ё": "e", "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k",
    "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r",
    "с": "s", "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts",
    "ч": "ch", "ш": "sh", "щ": "shch", "ъ": "", "ы": "y", "ь": "",
    "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Перевести русский текст в латиницу (прочие символы не меняются)."""
    return "".join(TRANSLIT.get(char, char) for char in text.lower())


def build_room_slug(number: str, pk: int) -> str:
    """Slug вида «auditoriya-301-1»: слово, номер и первичный ключ.

    Первичный ключ в конце гарантирует уникальность, даже если номера
    «12а» и «12a» после транслитерации совпадут.
    """
    base = slugify(transliterate(number)) or "room"
    return f"auditoriya-{base}-{pk}"
