"""Контекстный процессор Roomly (ПР10).

Функция вызывается Django при каждом рендеринге шаблона с request и
добавляет возвращённый словарь в контекст: значения доступны во всех
шаблонах (например, в base.html) без повторной передачи из каждого
представления.
"""

from rooms.models import Room


def room_context(request):
    """Общие данные для шаблонов: название сайта и число аудиторий."""
    return {
        "site_name": "Roomly",
        # count() выполняется базой данных (SELECT COUNT(*)), записи
        # в память не загружаются. Имя rooms_total, а не rooms_count:
        # главная страница уже передаёт свой rooms_count.
        "rooms_total": Room.objects.count(),
    }
